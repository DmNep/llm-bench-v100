#!/usr/bin/env python3
"""Собирает RESULTS.md из summary-*.csv обоих прогонов (iq4xs/, q4kxl/). Запуск: python -I make-results.py"""
import csv, glob, os, re

here = os.path.dirname(os.path.abspath(__file__))
STEPS = ["48K", "64K", "96K", "128K", "256K"]


def load(model):
    rows = []
    for s in STEPS:
        f = glob.glob(os.path.join(here, model, s, "summary-*.csv"))
        if not f:
            continue
        for r in csv.DictReader(open(f[0], encoding="utf-8")):
            rows.append((s, float(r["prompt_tokens"]), float(r["prefill_tps"]), float(r["gen_tps"]), float(r["draft_accept_pct"]), int(float(r["runs"]))))
    return rows


iq, q4 = load("iq4xs"), load("q4kxl")
assert len(iq) == len(q4) and len(iq) > 0


def pct(a, b):  # b относительно a
    d = (b - a) / a * 100
    return ("+" if d > 0 else "−" if d < 0 else "") + ("%d%%" % round(abs(d)))


def n(x, digits=0):
    s = ("{:,.%df}" % digits).format(x).replace(",", " ")
    return s.replace(".", ",")


out = []
out.append("# Strata на 96 ГБ ОЗУ: Qwen3.8-Flash-Next UD-IQ4_XS и UD-Q4_K_XL по окнам контекста\n")
out.append("""Стенд: Tesla V100 SXM2 32 ГБ на PCIe 3.0 x16, Ryzen 7 PRO 4750G, плата Gigabyte B550 GAMING X V2, **96 ГБ ОЗУ** (2×32 ГБ `FL3200D4U22-32G` + 2×16 ГБ, режим DDR4-2666), NVMe NX-512, Ubuntu 26.04.1, ядро 7.0.0-38, драйвер 580.178.04, CUDA 12.9. Память перед замерами прошла Memtest86+ (2 прохода по 96 ГБ, 0 ошибок). Замеры от 2026-10-10.

Движок Strata тот же бинарник, что и в замерах от 2026-10-07 (собран 2026-10-07 08:37); изменилась память сервера (48 → 96 ГБ) и бюджет экспертов.

Настройки: `--kv int8`, спекулятивная генерация (`--spec 4`, MTP), `--kv-resident 32768` с окна 64K и выше. **Бюджет экспертов в ОЗУ: IQ4_XS 55 ГиБ (все эксперты), Q4_K_XL 64 ГиБ (из 71,7 ГиБ, не все).** Картинки включены только у IQ4_XS (энкодер на GPU).

Метод тот же, что в остальных замерах (`bench.py`): случайный текст с уникальной меткой, 3 повтора (на 256K 2), медиана, `prompt_tokens` проверяется, 128 токенов генерации, размышление выключено, чтение и генерация считаются по ответу сервера. Разница в таблицах это отклонение Q4_K_XL от IQ4_XS.
""")

out.append("## Prefill (чтение запроса) и генерация по окнам\n")
out.append("| Окно | Запрос, токенов | Prefill IQ4_XS | Prefill Q4_K_XL | разница | Генерация IQ4_XS | Генерация Q4_K_XL | разница | Принято черновых IQ4_XS / Q4_K_XL, % |")
out.append("|---|---:|---:|---:|---:|---:|---:|---:|---|")
for a, b in zip(iq, q4):
    out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s / %s |" % (
        a[0], n(a[1]), n(a[2]), n(b[2]), pct(a[2], b[2]), n(a[3], 1), n(b[3], 1), pct(a[3], b[3]), n(a[4]), n(b[4])))
out.append("\nСкорости в ток/с.\n")

# средние по моделям
def avg(rows, idx, cond=lambda r: True):
    v = [r[idx] for r in rows if cond(r)]
    return sum(v) / len(v)

long_cond = lambda r: r[1] > 20000
out.append("**Средние по запросам больше 20 000 токенов:** IQ4_XS prefill %s, генерация %s ток/с; Q4_K_XL prefill %s (%s), генерация %s (%s).\n" % (
    n(avg(iq, 2, long_cond)), n(avg(iq, 3, long_cond), 1), n(avg(q4, 2, long_cond)), pct(avg(iq, 2, long_cond), avg(q4, 2, long_cond)),
    n(avg(q4, 3, long_cond), 1), pct(avg(iq, 3, long_cond), avg(q4, 3, long_cond))))

out.append("""## Основной тест (контекст 262 144, `--kv-resident 32768`, один запуск после холодного старта)

| Тест | IQ4_XS | Q4_K_XL |
|---|---:|---:|
| Холодный старт сервера до готовности, с | 58 | 117 |
| Генерация, первый запрос (холодный кэш экспертов), ток/с | 23,9 | 18,0 |
| Генерация, второй / третий запрос, ток/с | 36,8 / 42,5 | 30,0 / 36,6 |
| Генерация с размышлением (400 токенов), первый / второй, ток/с | 40,0 / 65,9 | 28,3 / 50,1 |
| Prefill 1K / 8K / 32K токенов, ток/с | 278 / 911 / 1 258 | 177 / 815 / 1 139 |
| Попадания в кэш экспертов в VRAM, % (первый → последний запрос) | 65 → 96 | 58 → 94 |
| Картинка (скриншот CrystalDiskMark, 217–236 токенов), ответ за | 6,9 с, затем 4,1 с | не поддерживается |
| Занято ОЗУ процессом, ГиБ | около 89 | около 62–77 |
""")

# сравнение с прошлыми замерами Q4_K_XL при 48 ГБ (из strata-q4-context/RESULTS.md, бюджет 21 ГиБ)
old = {  # (шаг, запрос ~) -> (prefill, gen)
    "1K": (87, 27.7), "25K": (547, 32.0), "66K": (560, 39.9), "128K": (481, 27.3),
}
def pick(rows, step, near):
    c = [r for r in rows if r[0] == step]
    return min(c, key=lambda r: abs(r[1] - near))

new_q4 = {
    "1K": pick(q4, "128K", 1094), "25K": pick(q4, "128K", 25025), "66K": pick(q4, "128K", 66646), "128K": pick(q4, "128K", 116910),
}
out.append("## Q4_K_XL: 48 ГБ ОЗУ (замер 2026-10-07) против 96 ГБ (сейчас)\n")
out.append("Окно 128K, тот же движок и методика. Тогда: 48 ГБ ОЗУ (16 + 32), бюджет экспертов 21 ГиБ. Сейчас: 96 ГБ, бюджет 64 ГиБ. Последняя строка: тогда запрос 128 087 токенов при окне 131 072, сейчас 116 909 (запрос больше не влез бы в окно вместе с ответом), поэтому сравнивать её нужно осторожно.\n")
out.append("| Запрос, токенов (сейчас) | Prefill 48 ГБ | Prefill 96 ГБ | во сколько раз | Генерация 48 ГБ | Генерация 96 ГБ | разница |")
out.append("|---|---:|---:|---:|---:|---:|---:|")
for k, label in (("1K", "1 094"), ("25K", "25 025"), ("66K", "66 646"), ("128K", "116 909")):
    o, nw = old[k], new_q4[k]
    out.append("| %s | %s | %s | ×%s | %s | %s | %s |" % (label, n(o[0]), n(nw[2]), n(nw[2] / o[0], 1), n(o[1], 1), n(nw[3], 1), pct(o[1], nw[3])))
out.append("")

out.append("""## Проверка прошлой экстраполяции

В `strata-q4-ram-budget/RESULTS.md` для 96 ГБ ОЗУ с бюджетом 71 ГиБ прогнозировалось: prefill 25K около **640** ток/с (+33%%), 66K около **850** (+60%%, верхняя оценка), генерация +0–25%%. Измерено на 96 ГБ при бюджете 64 ГиБ: prefill 25K **%s**, 66K **%s**, генерация на 25K %s, на 66K %s ток/с. Фактический выигрыш **значительно больше прогноза** (prefill вдвое выше прошлого замера против +33–60%% в прогнозе, генерация выше верхней границы +25%%). Экспоненциальная подгонка по точкам 4–21 ГиБ не учитывала, что при 96 ГБ оставшиеся 8 ГиБ экспертов целиком помещаются в кэш файловой системы и диск не читается совсем.
""" % (n(new_q4["25K"][2]), n(new_q4["66K"][2]), n(new_q4["25K"][3], 1), n(new_q4["66K"][3], 1)))

out.append("""## Что видно

- **IQ4_XS быстрее Q4_K_XL**: чтение запроса на 8–11% на длинных запросах (на коротких, 1K, на 25–28%), генерация в среднем на 10–15% (6–23% по точкам, шум большой); с размышлением 66 против 50 ток/с.
- **Скорость генерации почти не зависит от размера окна**: IQ4_XS около 54–62 ток/с от 1K до 239K запроса; Q4_K_XL 44–58. Prefill держится на 1 200–1 300 (IQ4_XS) и 1 100–1 190 ток/с (Q4_K_XL), на запросе 239K падает до 1 065 и 982.
- **Q4_K_XL вдвое дольше стартует** (117 против 58 с). Её бюджет 64 из 71,7 ГиБ: часть экспертов (около 8 ГиБ) читается через кэш файловой системы, а не лежит в бюджете, это возможная причина отставания. С бюджетом 72 ГиБ разрыв, вероятно, уменьшился бы; не проверялось (нужно около 100 ГиБ ОЗУ и больше, при 96 ГБ все 71,7 ГиБ экспертов с запасом на систему не помещаются).
- Первый запрос после старта всегда медленнее остальных (24 против 37–43 ток/с у IQ4_XS): кэш экспертов в VRAM прогревается; на размышлении попадания растут до 96%.

## Оговорки

- Один день, один стенд, по 2–3 повтора на точку; генерация шумит (разброс между повторами до 15–20%, принято черновых токенов 50–70%).
- Бюджет у моделей разный (IQ4_XS 55 ГиБ = все эксперты; Q4_K_XL 64 ГиБ из 71,7), сравнение «при одинаково полной памяти» для Q4_K_XL не проводилось.
- Качество ответов не оценивалось (только скорость); разные кванты дают разное качество, Q4_K_XL предположительно ближе к исходной точности.
- Тест кэша префикса в `strata-bench.py` (пункт `decode_ctx32k`) не информативен: модель ответила двумя токенами, его цифры не использовались.
- Картинки измерены только на IQ4_XS (на Q4_K_XL по документации Strata энкодер к этому файлу не подключён).

## Файлы

`iq4xs/` и `q4kxl/`: `raw-*.json` и `summary-*.csv` по каждому окну (`bench.py`), `*-main-ctx262144.json/.md` основной тест (`strata-bench.py`), `strata-bench.out` вывод. Таблицы собраны скриптом `make-results.py`.
""")

open(os.path.join(here, "RESULTS.md"), "w", encoding="utf-8").write("\n".join(out))
print("OK, строк:", len(out))
